package monada.neuron.evaluation.wave;

import java.util.List;

/**
 * Concept hierarchy of the {@code ncm-concept-fixture-v1} fixture (contract {@code ncm-wave-cognition/1} section
 * 12.3). The enum ordinal is the concept ordinal; parents precede their children.
 */
public enum FixtureConcept {

    /** Depth-0 category: dominant tone in the low band. */
    LOW_BAND(1, null),
    /** Depth-0 category: dominant tone in the high band. */
    HIGH_BAND(2, null),
    /** One low tone. */
    LOW_PURE(11, LOW_BAND),
    /** A low tone plus a second tone at 3/2 of its frequency. */
    LOW_CHORD(12, LOW_BAND),
    /** One high tone. */
    HIGH_PURE(21, HIGH_BAND),
    /** A high tone plus a second tone at 3/2 of its frequency. */
    HIGH_CHORD(22, HIGH_BAND);

    /** The leaf concepts in transition-table order; every window is generated by one of them. */
    public static final List<FixtureConcept> LEAVES = List.of(LOW_PURE, LOW_CHORD, HIGH_PURE, HIGH_CHORD);

    private final long code;
    private final FixtureConcept parent;

    FixtureConcept(long code, FixtureConcept parent) {
        this.code = code;
        this.parent = parent;
    }

    /** Returns the host's opaque concept code. */
    public long code() {
        return code;
    }

    /** Returns the parent ordinal, {@code -1} for a root. */
    public int parentOrdinal() {
        return parent == null ? -1 : parent.ordinal();
    }

    /** Returns {@code 0} for a category and {@code 1} for a leaf. */
    public int depth() {
        return parent == null ? 0 : 1;
    }

    /** Returns whether a window of this leaf has a second (chord) tone. */
    boolean chord() {
        return this == LOW_CHORD || this == HIGH_CHORD;
    }

    /** Returns whether this leaf's dominant tone lies in the low band. */
    boolean low() {
        return parent == LOW_BAND;
    }
}
