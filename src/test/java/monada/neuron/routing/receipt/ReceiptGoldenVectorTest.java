    enum Vector {
        SELECTED_NON_ASCII(SELECTED_HEX, SELECTED_SHA256),
        ABSTAIN_POLICY_TRADEOFF_UNRESOLVED(TRADEOFF_HEX, TRADEOFF_SHA256),
        ABSTAIN_STATE_INCOMPATIBLE(INCOMPATIBLE_HEX, INCOMPATIBLE_SHA256),
        NO_ELIGIBLE_ROUTE(NO_ELIGIBLE_ROUTE_HEX, NO_ELIGIBLE_ROUTE_SHA256);

        private final String hex;
        private final String sha256;

        Vector(String hex, String sha256) {
            this.hex = hex;
            this.sha256 = sha256;
        }

        RoutingDecision decision() {
            Parts parts = new Parts();
            return switch (this) {
                case SELECTED_NON_ASCII -> {
                    parts.taskId = "tâche-17";
                    yield parts.selected();
                }
                case ABSTAIN_POLICY_TRADEOFF_UNRESOLVED -> parts.tradeoff();
                case ABSTAIN_STATE_INCOMPATIBLE -> parts.incompatible();
                case NO_ELIGIBLE_ROUTE -> parts.noEligibleRoute();
            };
        }
    }

    // covers: AC-8
    @ParameterizedTest
    @EnumSource(Vector.class)
    void theCodecMatchesTheReferenceWriterAndTheCommittedBytes(Vector vector) {
        RoutingDecision decision = vector.decision();
        AdviceReceipt receipt = AdviceReceipt.of(decision);

        assertArrayEquals(ReferenceReceiptWriter.write(decision), receipt.bytes());
        assertEquals(vector.hex, HexFormat.of().formatHex(receipt.bytes()));
        assertEquals(vector.sha256, receipt.sha256());
    }

    // covers: AC-8
    @ParameterizedTest
    @EnumSource(Vector.class)
    void theCommittedBytesDecodeToTheVectorDecision(Vector vector) {
        var decoded = assertInstanceOf(DecodeResult.Decoded.class,
                AdviceReceipt.decode(HexFormat.of().parseHex(vector.hex)));

        assertEquals(vector.decision(), decoded.receipt().decision());
        assertEquals(vector.sha256, decoded.receipt().sha256());
    }
